"""Embed the properly renamed OFL pixel subset in the Go download page.
Maintainer-only; no toolchain or font download is needed on the Windows PC.
"""
from pathlib import Path
import base64
import sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from scripts.build_standalone import font_bytes
if __name__=='__main__':
    raw=font_bytes(ROOT/'assets/fonts/PressStart2P-Regular.ttf','Casardi Pixel')
    path=ROOT/'service/phone_font.go'
    path.write_text('// Generated by scripts/build_phone_font.py.\n// Press Start 2P subset, renamed Casardi Pixel. SIL OFL 1.1; see assets/fonts/OFL-PressStart2P.txt.\npackage main\n\nconst phoneFontData = "'+base64.b64encode(raw).decode()+'"\n')
    print('Embedded renamed Casardi Pixel WOFF:',len(raw),'bytes')
